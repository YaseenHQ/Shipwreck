// Fetches 3 real registry SVG icons and writes them as data URIs into
// preview/icons.js for the harness fixture.
const fs = require("fs");
const path = require("path");
const { get } = require("https");

const IDS = ["claude-acp", "codex-acp", "devin"];
const BASE = "https://cdn.agentclientprotocol.com/registry/v1/latest";

const body = (url) =>
  new Promise((res, rej) => {
    get(url, (r) => {
      let d = "";
      r.on("data", (c) => (d += c));
      r.on("end", () => (r.statusCode === 200 ? res(d) : rej(new Error(String(r.statusCode)))));
    }).on("error", rej);
  });

(async () => {
  const out = {};
  for (const id of IDS) {
    const svg = await body(`${BASE}/${id}.svg`);
    out[id] = "data:image/svg+xml;base64," + Buffer.from(svg, "utf8").toString("base64");
  }
  fs.writeFileSync(
    path.join(__dirname, "..", "preview", "icons.js"),
    "// generated by scripts/fetch-icons.js — real registry SVGs as data URIs\n" +
      "window.__agentIcons = " + JSON.stringify(out, null, 2) + ";\n",
  );
  console.log("wrote preview/icons.js:", Object.keys(out).join(", "));
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
