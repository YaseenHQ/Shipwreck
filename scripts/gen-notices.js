const esbuild = require("esbuild");
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const configs = [
  {
    entryPoints: ["src/extension.ts"],
    outfile: "dist/extension.js",
    external: ["vscode"],
    format: "cjs",
    platform: "node",
    target: "node18",
  },
  {
    entryPoints: ["src/ideBridge.ts"],
    outfile: "dist/ideBridge.js",
    format: "cjs",
    platform: "node",
    target: "node18",
  },
  {
    entryPoints: ["webview/main.tsx", "webview/styles.css"],
    outdir: "dist",
    outExtension: { ".js": ".webview.js" },
    format: "iife",
    platform: "browser",
    target: "es2020",
  },
];

async function main() {
  const builds = await Promise.all(configs.map((config) => esbuild.build({
    ...config,
    absWorkingDir: root,
    bundle: true,
    sourcemap: false,
    minify: true,
    logLevel: "info",
    write: false,
    metafile: true,
  })));
  const directories = new Set();
  for (const build of builds) {
    for (const output of Object.values(build.metafile.outputs)) {
      for (const [input, details] of Object.entries(output.inputs)) {
        if (details.bytesInOutput === 0) continue;
        const match = input.replace(/\\/g, "/").match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
        if (match) directories.add(match[1]);
      }
    }
  }
  const packages = [...directories].map((directory) => {
    const location = path.resolve(root, directory);
    const metadata = JSON.parse(fs.readFileSync(path.join(location, "package.json"), "utf8"));
    const files = fs.readdirSync(location)
      .filter((name) => /^(licen[cs]e|copying|notice)(?:$|[._-])/i.test(name))
      .filter((name) => fs.statSync(path.join(location, name)).isFile())
      .sort();
    if (!files.some((name) => /^(licen[cs]e|copying)(?:$|[._-])/i.test(name))) {
      throw new Error(`No license file for bundled package ${metadata.name}`);
    }
    if (!metadata.license) throw new Error(`No license declaration for ${metadata.name}`);
    const repository = typeof metadata.repository === "string"
      ? metadata.repository : metadata.repository?.url;
    if (!repository) throw new Error(`No repository for ${metadata.name}`);
    return {
      name: metadata.name,
      version: metadata.version,
      license: metadata.license,
      repository,
      files: files.map((name) => ({
        name,
        text: fs.readFileSync(path.join(location, name), "utf8"),
      })),
    };
  }).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);
  const sections = [
    "# Third-party notices",
    "Generated by `node scripts/gen-notices.js` from the production bundles and installed npm packages. Regenerate after changing dependencies or bundle entry points.",
    "Shipwreck's own code is licensed under GPL-3.0-or-later. See LICENSE. The third-party components below retain their respective licenses.",
    "## Bundled npm packages",
  ];
  for (const pkg of packages) {
    sections.push(
      `### ${pkg.name}@${pkg.version}`,
      `License: ${pkg.license}\n\nRepository: ${pkg.repository}`,
    );
    for (const file of pkg.files) {
      sections.push(`#### ${file.name}`, "```text\n" + file.text + (file.text.endsWith("\n") ? "" : "\n") + "```");
    }
  }
  const purify = fs.readFileSync(path.join(root, "node_modules/dompurify/dist/purify.es.mjs"), "utf8");
  const purifyNotice = purify.match(/\/\*![^\n]*@license DOMPurify[^\n]*\*\//)?.[0];
  const helperNotice = purify.match(/\/\*![^\n]*regenerator-runtime[^\n]*\*\//)?.[0];
  const copyright = helperNotice?.match(/Copyright \(c\) .*?(?= -- license)/)?.[0];
  if (!purifyNotice || !helperNotice || !copyright || !helperNotice.includes("(MIT)")) {
    throw new Error("DOMPurify or embedded helper license header changed");
  }
  const mit = fs.readFileSync(path.join(root, "node_modules/react/LICENSE"), "utf8");
  const permission = mit.indexOf("Permission is hereby granted");
  if (permission === -1) throw new Error("Cannot find the MIT license terms");
  const phosphor = packages.find((pkg) => pkg.name === "@phosphor-icons/react");
  const iconLicense = phosphor?.files.find((file) => /^LICENSE$/i.test(file.name));
  if (!iconLicense) throw new Error("Cannot find the Phosphor icon asset license");
  sections.push(
    "## DOMPurify license election",
    "DOMPurify is offered under MPL-2.0 OR Apache-2.0. Shipwreck elects Apache-2.0 for its bundled copy. The Apache license text is reproduced in DOMPurify's LICENSE section above. The alternative MPL text is retained there for completeness.",
    "```text\n" + purifyNotice + "\n```",
    "## MIT helpers embedded in DOMPurify",
    "DOMPurify's distributed JavaScript embeds regenerator-runtime and Babel helper code. Its original comment header follows. The MIT permission and warranty terms are reproduced from the bundled React MIT license.",
    "```text\n" + helperNotice + "\n\nMIT License\n\n" + copyright + "\n\n" + mit.slice(permission) + "```",
    "## Phosphor-derived icon assets",
    "The SVG paths in `media/icons/` are from Phosphor Icons, and `scripts/gen-fill-icons.js` derives the filled variants. These assets retain the following MIT notice.",
    "```text\n" + iconLicense.text + "```",
    "## Trademarks and runtime agent logos",
    "Agent names, trademarks, and logos belong to their respective owners. Agent names and logo URLs come from the ACP registry at runtime, and the logos are downloaded at runtime rather than bundled in this extension. Their display identifies supported agents and does not imply endorsement or grant trademark rights.",
  );
  fs.writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), sections.join("\n\n") + "\n");
  console.log("Bundled packages:\n" + packages.map((pkg) => `${pkg.name}@${pkg.version} (${pkg.license})`).join("\n"));
  console.log("wrote THIRD_PARTY_NOTICES.md");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
